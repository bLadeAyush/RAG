from pathlib import Path
def load_document(path):
    """Load a text document."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f"File not found: {path}"
        )
    if not path.is_file():
        raise ValueError(
            f"Not a file: {path}"
        )
    if path.suffix.lower() != ".txt":
        raise ValueError(
            "Only .txt files are supported"
        )
    with open(path, "r", encoding="utf-8") as f:
        return f.read()

def preprocess_text(text):
    """Clean whitespace."""
    if text is None:
        raise ValueError("text cannot be None")
    text = text.strip()
    text = " ".join(text.split())
    return text

def chunk_text(text, chunk_size=100, overlap=20):
    """Split text into overlapping word chunks."""
    if chunk_size <= 0:
        raise ValueError(
            "chunk_size must be greater than 0"
        )
    if overlap < 0 or overlap >= chunk_size:
        raise ValueError(
            "overlap must be >= 0 and < chunk_size"
        )
    text = preprocess_text(text)
    if not text:
        return []
    words = text.split()
    chunks = []
    start = 0
    while start < len(words):
        end = start + chunk_size
        chunk = " ".join(
            words[start:end]
        )
        chunks.append(chunk)
        start = end - overlap
    return chunks

from fastembed import TextEmbedding
class EmbeddingModel:
    def __init__(
        self,
        model_name="BAAI/bge-small-en-v1.5"
    ):
        self.model = TextEmbedding(
            model_name=model_name
        )
    def embed(self, texts):
        """Convert text into embedding vectors."""
        if not texts:
            return []
        return list(
            self.model.embed(texts)
        )

import math
class VectorStore:
    def __init__(self):
        self.documents = []
        self.embeddings = []
    def add_documents(
        self,
        documents,
        embeddings
    ):
        """Store documents and their vectors."""
        if len(documents) != len(embeddings):
            raise ValueError(
                "Documents and embeddings "
                "must have the same length"
            )
        for doc, embedding in zip(
            documents,
            embeddings
        ):
            self.documents.append(doc)
            self.embeddings.append(
                list(embedding)
            )
    def cosine_similarity(self, a, b):
        """Calculate cosine similarity."""
        if len(a) != len(b):
            raise ValueError(
                "Vector dimensions must match"
            )
        dot = sum(
            x * y
            for x, y in zip(a, b)
        )
        mag_a = math.sqrt(
            sum(x * x for x in a)
        )
        mag_b = math.sqrt(
            sum(x * x for x in b)
        )
        if mag_a == 0 or mag_b == 0:
            return 0.0
        return dot / (mag_a * mag_b)
    def search(
        self,
        query_embedding,
        k=3
    ):
        """Return top-k similar documents."""
        if not query_embedding:
            return []
        scores = []
        for doc, embedding in zip(
            self.documents,
            self.embeddings
        ):
            score = self.cosine_similarity(
                query_embedding,
                embedding
            )
            scores.append(
                (doc, score)
            )
        scores.sort(
            key=lambda x: x[1],
            reverse=True
        )
        return scores[:k]

